#!/usr/bin/env python3
"""Regenerates the macOS string tables from the Windows ones, so both apps share one
set of translations. Mac-only wording lives in src/Mac/Sources/FlectKit/I18n/Strings+Mac.swift.

    python3 scripts/mac/sync-strings.py
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "src", "I18n")
TARGET = os.path.join(ROOT, "src", "Mac", "Sources", "FlectKit", "I18n")

# The "app" section holds the strings of the Windows app, which the Mac app shares.
TABLES = [
    ("en.json", "English", "english"),
    ("ja.json", "Japanese", "japanese"),
    ("zh.json", "Chinese", "chinese"),
]


def swift_literal(text):
    out = []
    for character in text:
        if character == "\\":
            out.append("\\\\")
        elif character == '"':
            out.append('\\"')
        elif character == "\n":
            out.append("\\n")
        elif character == "\r":
            out.append("\\r")
        elif character == "\t":
            out.append("\\t")
        elif ord(character) < 0x20:
            out.append("\\u{%x}" % ord(character))
        else:
            out.append(character)
    return "".join(out)


def main():
    os.makedirs(TARGET, exist_ok=True)
    for source, suffix, name in TABLES:
        with open(os.path.join(SOURCE, source), encoding="utf-8-sig") as handle:
            pairs = list(json.load(handle).get("app", {}).items())
        if not pairs:
            sys.stderr.write("No app strings found in %s\n" % source)
            return 1
        lines = [
            "// Generated by scripts/mac/sync-strings.py from src/I18n/%s. Do not edit." % source,
            "",
            "extension Strings {",
            "    static let %s: [String: String] = [" % name,
        ]
        for key, value in pairs:
            lines.append('        "%s": "%s",' % (swift_literal(key), swift_literal(value)))
        lines += ["    ]", "}", ""]
        with open(os.path.join(TARGET, "Strings+%s.swift" % suffix), "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines))
        print("%s: %d strings" % (source, len(pairs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
