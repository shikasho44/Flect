#!/usr/bin/env python3
"""Regenerates the macOS string tables from the Windows ones, so both apps share one
set of translations. Mac-only wording lives in src/Mac/Sources/FlectKit/I18n/Strings+Mac.swift.

    python3 scripts/mac/sync-strings.py
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "src", "App", "Main", "I18n")
TARGET = os.path.join(ROOT, "src", "Mac", "Sources", "FlectKit", "I18n")

TABLES = [
    ("Strings.En.cs", "English", "english"),
    ("Strings.Ja.cs", "Japanese", "japanese"),
    ("Strings.Zh.cs", "Chinese", "chinese"),
]

ENTRY = re.compile(r'^\s*\["(?P<key>[^"]+)"\]\s*=\s*"(?P<value>(?:[^"\\]|\\.)*)"\s*,?\s*$')


def entries(path):
    found = []
    with open(path, encoding="utf-8-sig") as handle:
        for line in handle:
            match = ENTRY.match(line)
            if match:
                found.append((match.group("key"), match.group("value")))
    return found


def swift_literal(csharp):
    return csharp.replace("\\'", "'")


def main():
    os.makedirs(TARGET, exist_ok=True)
    for source, suffix, name in TABLES:
        pairs = entries(os.path.join(SOURCE, source))
        if not pairs:
            sys.stderr.write("No strings found in %s\n" % source)
            return 1
        lines = [
            "// Generated by scripts/mac/sync-strings.py from src/App/Main/I18n/%s. Do not edit." % source,
            "",
            "extension Strings {",
            "    static let %s: [String: String] = [" % name,
        ]
        for key, value in pairs:
            lines.append('        "%s": "%s",' % (key, swift_literal(value)))
        lines += ["    ]", "}", ""]
        with open(os.path.join(TARGET, "Strings+%s.swift" % suffix), "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines))
        print("%s: %d strings" % (source, len(pairs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
